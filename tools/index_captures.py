#!/usr/bin/env python3
"""Regenerate captures/INDEX.md from the capture sidecars.

Capture filenames are timestamps and carry no meaning; the sidecar JSON records
what each one was for, the settings used, and the probe map in force. This turns
that into a readable table so the evidence set is navigable.
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CAP = REPO / "captures"


def main() -> int:
    rows = []
    for j in sorted(CAP.glob("*.json")):
        d = json.loads(j.read_text())
        s = d.get("session", {})
        stem = j.stem
        data = next((p.name for p in (CAP / f"{stem}.csv.gz", CAP / f"{stem}.csv") if p.exists()), None)
        n_ch = len(s.get("CaptureChannels", []))
        total = s.get("PostTriggerSamples", 0) * (s.get("LoopCount", 0) + 1) + s.get("PreTriggerSamples", 0)
        rows.append({
            "id": stem,
            "ok": bool(data),
            "rate": s.get("Frequency"),
            "ch": n_ch,
            "samples": total,
            "bursts": s.get("LoopCount", 0) + 1,
            "note": (d.get("note") or "").strip(),
            "probe_map": d.get("probe_map", ""),
        })

    out = ["# Capture index", "",
           "Generated by `tools/index_captures.py`. Do not edit by hand.", "",
           "Captures are stored gzipped (~110:1); every tool loads `.csv` and `.csv.gz`",
           "interchangeably via `tools/capio.py`. Each has a `.json` sidecar recording the",
           "full settings, the probe-map version in force, and a free-text note.", "",
           "Filenames all carry the `dryrun` preset name because every capture was driven",
           "through that preset with explicit overrides — it is **not** an indication that",
           "the capture is a throwaway. Read the note column.", "",
           f"| capture | rate | ch | samples | bursts | purpose |",
           "|---|---:|---:|---:|---:|---|"]
    for r in rows:
        rate = f"{r['rate']/1e6:g} MS/s" if r["rate"] else "—"
        note = r["note"].replace("|", "/")
        if len(note) > 150:
            note = note[:147] + "…"
        mark = "" if r["ok"] else " *(failed, no data)*"
        out.append(f"| `{r['id']}`{mark} | {rate} | {r['ch']} | {r['samples']} | "
                   f"{r['bursts']} | {note} |")
    out.append("")
    (CAP / "INDEX.md").write_text("\n".join(out) + "\n")
    ok = sum(1 for r in rows if r["ok"])
    print(f"wrote captures/INDEX.md — {len(rows)} sidecars, {ok} with data")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
