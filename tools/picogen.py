"""Drive a MicroPython Pico as a known-signal generator for toolchain validation.

Used in phase 0 to produce a signal whose frequency and duty cycle we know
exactly, so a capture can be checked against ground truth rather than merely
"looking plausible".

    tools/picogen.py pwm --freq 10000        # default: GP15 @50%, GP14 @25%
    tools/picogen.py stop
    tools/picogen.py info
"""
from __future__ import annotations

import argparse
import glob
import sys
import time

try:
    import serial
except ImportError:
    sys.exit("pyserial is required:  python3 -m pip install pyserial")

# GP14/GP15 are the two channels of the same RP2040 PWM slice, so they share a
# frequency but can carry different duty cycles -- two distinguishable signals
# with one known period.
DEFAULT_PINS = [(15, 50.0), (14, 25.0)]


def find_pico() -> str:
    hits = glob.glob("/dev/serial/by-id/*MicroPython*")
    if len(hits) == 1:
        return hits[0]
    if not hits:
        sys.exit("no MicroPython board found under /dev/serial/by-id/")
    sys.exit(f"multiple MicroPython boards found: {hits}; pass --port")


class Pico:
    def __init__(self, port: str):
        self.s = serial.Serial(port, 115200, timeout=3)
        self.s.write(b"\x03\x03")           # Ctrl-C: interrupt anything running
        time.sleep(0.2)
        self.s.reset_input_buffer()
        self.s.write(b"\x01")               # Ctrl-A: raw REPL
        time.sleep(0.2)
        if b"raw REPL" not in self.s.read(200):
            sys.exit("could not enter the MicroPython raw REPL")

    def run(self, code: str) -> str:
        self.s.write(code.encode() + b"\x04")
        time.sleep(0.4)
        out = self.s.read(4000).decode(errors="replace")
        if "Traceback" in out or "Error" in out:
            sys.exit(f"MicroPython error:\n{out}")
        return out.lstrip("OK").rstrip("\x04>").strip()

    def write_file(self, name: str, content: str) -> None:
        """Write a file to the board's filesystem in chunks the REPL can absorb."""
        self.run(f"f=open({name!r},'w')")
        for i in range(0, len(content), 256):
            self.run(f"f.write({content[i:i + 256]!r})")
        self.run("f.close()")

    def reset(self) -> str:
        """Soft-reset and return whatever the board prints as it boots."""
        self.s.write(b"\x02")               # leave raw REPL first
        time.sleep(0.2)
        self.s.reset_input_buffer()
        self.s.write(b"\x04")               # Ctrl-D: soft reset, runs main.py
        time.sleep(1.5)
        return self.s.read(4000).decode(errors="replace")

    def close(self):
        self.s.write(b"\x02")               # back to the friendly REPL
        self.s.close()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["pwm", "stop", "info"])
    ap.add_argument("--port", help="serial port (default: autodetect by-id)")
    ap.add_argument("--freq", type=int, default=10_000, help="PWM frequency in Hz")
    ap.add_argument("--pins", help="comma-separated gpio:duty%% pairs, e.g. 15:50,14:25")
    args = ap.parse_args()

    pins = DEFAULT_PINS
    if args.pins:
        pins = [(int(p.split(":")[0]), float(p.split(":")[1])) for p in args.pins.split(",")]

    pico = Pico(args.port or find_pico())
    try:
        if args.cmd == "info":
            print(pico.run("import sys, machine\n"
                           "print(sys.implementation._machine, machine.freq())"))
        elif args.cmd == "stop":
            pico.run("import os\n"
                     "try:\n"
                     "    os.remove('main.py')\n"
                     "except OSError:\n"
                     "    pass")
            pico.reset()
            print("removed main.py and reset; no signal is being generated")
        else:
            # Persist to main.py rather than driving from the REPL. A PWM object
            # created in a REPL scope becomes garbage as soon as the block ends,
            # and MicroPython's finaliser deinits the pin -- the signal silently
            # dies. Holding module-level references in main.py also means the
            # signal survives a reset or a USB replug, so an armed capture cannot
            # be defeated by the generator going away.
            body = ["# generated by tools/picogen.py -- known-signal source", "",
                    "from machine import Pin, PWM", "", "_pwms = []  # keep refs alive", ""]
            for gpio, duty in pins:
                body += [f"_p = PWM(Pin({gpio}))",
                         f"_p.freq({args.freq})",
                         f"_p.duty_u16({int(round(duty / 100.0 * 65535))})",
                         "_pwms.append(_p)",
                         f"print('GP{gpio}', _p.freq(), 'Hz', {duty}, '%')", ""]
            pico.write_file("main.py", "\n".join(body) + "\n")
            print(f"deployed main.py (requested {args.freq} Hz)")
            banner = pico.reset()
            print("after reset, board reports:")
            for line in banner.splitlines():
                if line.strip().startswith("GP"):
                    print(f"  {line.strip()}")
            print("\nNOTE: the RP2040 divider quantises the frequency; the value "
                  "reported above is what the hardware actually produces and is what "
                  "the capture must be checked against.")
    finally:
        pico.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
