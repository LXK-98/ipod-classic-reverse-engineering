"""Deploy and drive the breadboard panel driver (firmware/ on a MicroPython Pico).

    tools/drv.py deploy                    # firmware + init sequences -> Pico
    tools/drv.py status
    tools/drv.py cycle [--hold-ms 30]      # milestone 1: up, hold, down in one call
    tools/drv.py up [--gap-ms 218] [--ref-lead-us 1000]
    tools/drv.py down
    tools/drv.py init [--variant init|awake] [--wait-ms 400]
    tools/drv.py te [--ms 1000]            # did init take? TE should run at ~67.9 Hz
    tools/drv.py fill R G B                # 6-bit channel values, 0..63
    tools/drv.py ramp [rgb|r|g|b] [--band 5]

Each call is one connection. The Pico keeps its state between calls (entering
the raw REPL does not reset it), so `up`, then `init`, then `ramp` is a valid
sequence of separate commands. Wiring and procedure: docs/BREADBOARD.md.

Needs pyserial (requirements.txt); the init-sequence generator does not, so
firmware/test_host.py can import this module without it.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FIRMWARE = REPO / "firmware"
SEQUENCES = REPO / "refs" / "sequences.json"

# Which refs/sequences.json entries the firmware carries, and why.
#   init  -- what the original sends at every cold boot (DRIVING.md section 6)
#   awake -- the 152-write variant, init preceded by six CMD 0x0000
#   sleep -- sent before power-down; that the original uses THIS one is an
#            inference (TE stops before power is cut; the command was never captured)
CARRIED = {
    "init": ("bootloader", "init"),
    "awake": ("firmware", "awake"),
    "sleep": ("firmware", "sleep"),
}
UPLOAD = ("bus.py", "lcddrv.py")


def sequence(config: str, name: str, ptype: str = "2") -> tuple:
    """refs/sequences.json -> ((kind, value), ...) in firmware/bus.py's terms."""
    tx = json.loads(SEQUENCES.read_text())["configs"][config]["types"][ptype]["sequences"][name]["transactions"]
    out = []
    for e in tx:
        if e["kind"] == "sleep":
            out.append((2, int(round(e["ms"] * 1000))))     # bus.SLEEP, microseconds
        else:
            out.append((0 if e["kind"] == "cmd" else 1, e["value"]))
    return tuple(out)


def initseq_source() -> str:
    lines = ["# Generated by tools/drv.py from refs/sequences.json -- do not edit.",
             "# (kind, value): 0 = CMD, 1 = DATA, 2 = sleep in microseconds.", "SEQ = {"]
    for key, (config, name) in CARRIED.items():
        lines.append(f"    {key!r}: {sequence(config, name)!r},  # {config}.types.2.{name}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def connect():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from picogen import Pico, find_pico   # needs pyserial; imported only when talking to a board

    class Driver(Pico):
        def exec(self, code: str, timeout: float = 30.0) -> str:
            """Run code in the raw REPL and wait for its end markers, not a fixed
            sleep: power_up and init legitimately take most of a second."""
            data = code.encode()
            for i in range(0, len(data), 256):
                self.s.write(data[i:i + 256])
                time.sleep(0.01)            # do not overrun the board's input buffer
            self.s.write(b"\x04")
            buf = bytearray()
            deadline = time.monotonic() + timeout
            # Reply: b"OK" stdout b"\x04" stderr b"\x04" b">"
            while not (buf.endswith(b"\x04>") and buf.count(b"\x04") >= 2):
                if time.monotonic() > deadline:
                    raise SystemExit(f"no reply within {timeout:g} s; got {bytes(buf)!r}")
                buf += self.s.read(self.s.in_waiting or 1)
            if not buf.startswith(b"OK"):
                raise SystemExit(f"raw REPL refused the code: {bytes(buf)!r}")
            out, err = bytes(buf[2:-2]).split(b"\x04", 1)
            if err:
                raise SystemExit("error on the Pico:\n" + err.decode(errors="replace"))
            return out.decode(errors="replace").strip()

        def put_file(self, name: str, text: str) -> None:
            self.exec(f"_f = open({name!r}, 'w')")
            for i in range(0, len(text), 512):
                self.exec(f"_f.write({text[i:i + 512]!r})")
            self.exec("_f.close()")
            got = int(self.exec(f"import os; print(os.stat({name!r})[6])"))
            if got != len(text.encode()):
                raise SystemExit(f"{name}: wrote {got} bytes, expected {len(text.encode())}")

    return Driver, find_pico


def deploy(pico) -> None:
    for name in UPLOAD:
        if not (FIRMWARE / name).read_text().isascii():
            raise SystemExit(f"firmware/{name} must be ASCII-only")
    # Never replace the driver under live rails: power down the old one first.
    pico.exec("import sys\nif 'lcddrv' in sys.modules: sys.modules['lcddrv'].power_down()")
    if pico.exec("import os; print('main.py' in os.listdir())") == "True":
        # e.g. picogen.py's PWM generator, which drives GP14/GP15 -- two data lanes
        pico.exec("import os; os.remove('main.py')")
        print("removed main.py from the board (it would drive GPIOs at boot)")
    for name in UPLOAD:
        pico.put_file(name, (FIRMWARE / name).read_text())
        print(f"  {name}")
    pico.put_file("initseq.py", initseq_source())
    print("  initseq.py (generated)")
    pico.exec("import sys\nfor m in ('lcddrv', 'bus', 'initseq'): sys.modules.pop(m, None)")
    print(pico.exec("import lcddrv as d, initseq\n"
                    "print('writes:', {k: sum(1 for e in v if e[0] != 2) for k, v in initseq.SEQ.items()})\n"
                    "print(d.status())"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--port", help="serial port (default: autodetect the MicroPython board)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("deploy")
    sub.add_parser("status")
    sub.add_parser("down")
    p = sub.add_parser("cycle")
    p.add_argument("--hold-ms", type=int, default=30)
    p = sub.add_parser("up")
    p.add_argument("--gap-ms", type=int, help="reference -> VDDIO (default 218)")
    p.add_argument("--ref-lead-us", type=int, help="3.0 V -> reference (default 1000)")
    p = sub.add_parser("init")
    p.add_argument("--variant", choices=("init", "awake"), default="init")
    p.add_argument("--wait-ms", type=int, help="minimum VDDIO -> first command (default 400)")
    p = sub.add_parser("te")
    p.add_argument("--ms", type=int, default=1000)
    p = sub.add_parser("fill")
    for c in "rgb":
        p.add_argument(c, type=int, choices=range(64), metavar=c.upper())
    p = sub.add_parser("ramp")
    p.add_argument("which", nargs="?", default="rgb", choices=("rgb", "r", "g", "b"))
    p.add_argument("--band", type=int, default=5)
    args = ap.parse_args()

    def kw(**k) -> str:
        return ", ".join(f"{a}={v!r}" for a, v in k.items() if v is not None)

    calls = {
        "status": "print(d.status())",
        "down": "d.power_down(); print(d.status())",
        "cycle": f"d.cycle(hold_ms={getattr(args, 'hold_ms', 0)}); print(d.status())",
        "up": f"d.power_up({kw(gap_ms=getattr(args, 'gap_ms', None), ref_lead_us=getattr(args, 'ref_lead_us', None))}); print(d.status())",
        "init": f"d.init({kw(variant=getattr(args, 'variant', None), wait_ms=getattr(args, 'wait_ms', None))}); print('TE edges, Hz:', d.te_rate(500))",
        "te": f"print('TE edges, Hz:', d.te_rate({getattr(args, 'ms', 0)}))",
        "fill": f"d.fill({getattr(args, 'r', 0)}, {getattr(args, 'g', 0)}, {getattr(args, 'b', 0)})",
        "ramp": f"d.ramp({getattr(args, 'which', 'rgb')!r}, {getattr(args, 'band', 5)})",
    }

    Driver, find_pico = connect()
    pico = Driver(args.port or find_pico())
    try:
        if args.cmd == "deploy":
            deploy(pico)
        else:
            out = pico.exec("import lcddrv as d\n" + calls[args.cmd])
            if out:
                print(out)
    finally:
        pico.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
